CREATE OR REPLACE FUNCTION public.protect_user_profile_identity()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_claim_owner NAME;
BEGIN
  SELECT pg_catalog.pg_get_userbyid(routine.proowner)
  INTO v_claim_owner
  FROM pg_catalog.pg_proc routine
  WHERE routine.oid = 'public.claim_education_establishment_as_user(text,uuid)'::regprocedure;

  IF COALESCE(auth.jwt()->>'role', '') <> 'service_role' AND auth.uid() = OLD.user_id THEN
    NEW.role := OLD.role;
    NEW.user_id := OLD.user_id;
    IF CURRENT_USER <> v_claim_owner THEN
      NEW.school_id := OLD.school_id;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

