AS $$
BEGIN
  UPDATE public.schools
  SET education_establishment_id = NEW.id,
      education_link_status = 'linked',
      updated_at = now()
  WHERE education_establishment_id IS NULL
    AND external_id IS NOT NULL
    AND public.normalize_uai(external_id) = NEW.uai
