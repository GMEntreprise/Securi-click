CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_meta JSONB := COALESCE(NEW.raw_user_meta_data, '{}'::jsonb);
  v_role TEXT := COALESCE(NULLIF(v_meta->>'role', ''), 'parent');
  v_first TEXT;
  v_last TEXT;
  v_phone TEXT;
  v_claim JSONB;
BEGIN
  IF v_role NOT IN ('parent', 'school_admin') THEN
    v_role := 'parent';
  END IF;

  v_first := COALESCE(NULLIF(v_meta->>'first_name', ''), NULLIF(v_meta->>'manager_first_name', ''), '');
  v_last := COALESCE(NULLIF(v_meta->>'last_name', ''), NULLIF(v_meta->>'manager_last_name', ''), '');
  v_phone := NULLIF(v_meta->>'phone', '');

  INSERT INTO public.user_profiles (user_id, first_name, last_name, phone, role)
  VALUES (NEW.id, v_first, v_last, v_phone, v_role)
  ON CONFLICT (user_id) DO NOTHING;

  IF v_role = 'school_admin' THEN
    IF COALESCE(v_meta->>'directory_uai', '') = '' THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'directory_uai_required';
    END IF;
    v_claim := public.claim_education_establishment_as_user(v_meta->>'directory_uai', NEW.id);
    IF v_claim->>'status' <> 'claimed' THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'establishment_' || COALESCE(v_claim->>'status', 'claim_failed');
    END IF;
    UPDATE public.schools
    SET manager_function = COALESCE(NULLIF(v_meta->>'manager_function', ''), manager_function),
        updated_at = now()
    WHERE id = (v_claim->>'school_id')::uuid;
  END IF;

  RETURN NEW;
END;
