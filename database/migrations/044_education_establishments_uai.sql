CREATE OR REPLACE FUNCTION public.claim_education_establishment_as_user(p_uai TEXT, p_user_id UUID)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user_id UUID := p_user_id;
  v_establishment public.education_establishments%ROWTYPE;
  v_school_id UUID;
  v_school_admin_user_id UUID;
  v_profile public.user_profiles%ROWTYPE;
  v_email TEXT;
BEGIN
  IF v_user_id IS NULL THEN
    RETURN jsonb_build_object('status', 'unauthorized');
  END IF;
  IF public.normalize_uai(p_uai) !~ '^[0-9]{7}[A-Z]$' THEN
    RETURN jsonb_build_object('status', 'invalid_uai');
  END IF;

  SELECT e.* INTO v_establishment
  FROM public.education_establishments e
  WHERE e.uai = public.normalize_uai(p_uai)
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('status', 'not_found');
  END IF;
  IF NOT v_establishment.is_active THEN
    RETURN jsonb_build_object('status', 'inactive');
  END IF;

  SELECT up.* INTO v_profile
  FROM public.user_profiles up
  WHERE up.user_id = v_user_id;

  IF NOT FOUND OR v_profile.role <> 'school_admin' THEN
    RETURN jsonb_build_object('status', 'forbidden');
  END IF;

  SELECT s.id, s.admin_user_id INTO v_school_id, v_school_admin_user_id
  FROM public.schools s
  WHERE s.education_establishment_id = v_establishment.id;

  IF v_school_admin_user_id IS NOT NULL
     AND v_school_admin_user_id <> v_user_id THEN
    RETURN jsonb_build_object('status', 'already_claimed');
  END IF;

  IF v_school_admin_user_id IS NULL THEN
    SELECT u.email INTO v_email FROM auth.users u WHERE u.id = v_user_id;

    IF v_school_id IS NOT NULL THEN
      UPDATE public.schools
      SET name = v_establishment.official_name,
          type = v_establishment.nature_label,
          email = COALESCE(v_email, 'school+' || v_user_id::text || '@securiclick.invalid'),
          phone = COALESCE(v_profile.phone, ''),
          address = COALESCE(v_establishment.address_line_1, v_establishment.city),
          city = v_establishment.city,
          postal_code = v_establishment.postal_code,
          manager_first_name = v_profile.first_name,
          manager_last_name = v_profile.last_name,
          manager_function = 'Responsable',
          admin_user_id = v_user_id,
          verified = true,
          external_id = v_establishment.uai,
          external_source = v_establishment.source,
          synced_at = v_establishment.synced_at,
          education_link_status = 'linked',
          is_active = true,
          updated_at = now()
      WHERE id = v_school_id
        AND admin_user_id IS NULL
      RETURNING id INTO v_school_id;
    ELSE
      INSERT INTO public.schools (
        name, type, email, phone, address, city, postal_code,
        manager_first_name, manager_last_name, manager_function,
        admin_user_id, verified, external_id, external_source, synced_at,
        education_establishment_id, education_link_status
      ) VALUES (
        v_establishment.official_name,
        v_establishment.nature_label,
        COALESCE(v_email, 'school+' || v_user_id::text || '@securiclick.invalid'),
        COALESCE(v_profile.phone, ''),
        COALESCE(v_establishment.address_line_1, v_establishment.city),
        v_establishment.city,
        v_establishment.postal_code,
        v_profile.first_name,
        v_profile.last_name,
        'Responsable',
        v_user_id,
        true,
        v_establishment.uai,
        v_establishment.source,
        v_establishment.synced_at,
        v_establishment.id,
        'linked'
      )
      ON CONFLICT (education_establishment_id) WHERE education_establishment_id IS NOT NULL
      DO NOTHING
      RETURNING id INTO v_school_id;
    END IF;
  END IF;

  IF v_school_id IS NULL THEN
    RETURN jsonb_build_object('status', 'already_claimed');
  END IF;

  UPDATE public.user_profiles
  SET school_id = v_school_id, updated_at = now()
  WHERE user_id = v_user_id;

  UPDATE public.school_memberships
  SET role = 'school_admin', is_active = true
  WHERE school_id = v_school_id
    AND user_id = v_user_id;

  IF NOT FOUND THEN
    INSERT INTO public.school_memberships (school_id, user_id, role, is_active)
    VALUES (v_school_id, v_user_id, 'school_admin', true);
  END IF;

  RETURN jsonb_build_object('status', 'claimed', 'school_id', v_school_id);
END;
$$;

