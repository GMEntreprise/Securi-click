CREATE OR REPLACE FUNCTION public.search_education_establishments(
  p_query TEXT,
  p_page INTEGER DEFAULT 0,
  p_page_size INTEGER DEFAULT 20
)
RETURNS TABLE (
  id UUID,
  uai TEXT,
  official_name TEXT,
  nature_label TEXT,
  sector TEXT,
  has_nursery BOOLEAN,
  has_elementary BOOLEAN,
  school_level TEXT,
  address_line_1 TEXT,
  address_line_2 TEXT,
  address_line_3 TEXT,
  postal_code TEXT,
  city TEXT,
  department_name TEXT,
  academy TEXT,
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  is_active BOOLEAN,
  source_updated_at DATE,
  is_claimed BOOLEAN,
  rank_score INTEGER
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, extensions
AS $$
  WITH input AS (
    SELECT trim(COALESCE(p_query, '')) AS raw,
           public.normalize_school_name(COALESCE(p_query, '')) AS normalized,
           public.normalize_uai(COALESCE(p_query, '')) AS possible_uai,
           LEAST(GREATEST(COALESCE(p_page_size, 20), 1), 50) AS page_size,
           GREATEST(COALESCE(p_page, 0), 0) AS page_number
  )
  SELECT e.id, e.uai, e.official_name, e.nature_label, e.sector,
         e.has_nursery, e.has_elementary, e.school_level,
         e.address_line_1, e.address_line_2, e.address_line_3,
         e.postal_code, e.city, e.department_name, e.academy,
         e.latitude, e.longitude, e.is_active, e.source_updated_at,
         EXISTS (
           SELECT 1 FROM public.schools s
           WHERE s.education_establishment_id = e.id
             AND s.admin_user_id IS NOT NULL
         ) AS is_claimed,
         CASE
           WHEN e.uai = i.possible_uai THEN 100
           WHEN e.postal_code = i.raw THEN 95
           WHEN public.normalize_school_name(e.official_name) = i.normalized THEN 90
           WHEN public.normalize_school_name(e.official_name) LIKE i.normalized || '%' THEN 85
           WHEN public.normalize_school_name(e.city) = i.normalized THEN 80
           WHEN public.normalize_school_name(e.official_name) LIKE '%' || i.normalized || '%' THEN 75
           ELSE GREATEST(
             round(similarity(public.normalize_school_name(e.official_name), i.normalized) * 70)::integer,
             round(similarity(public.normalize_school_name(e.city), i.normalized) * 65)::integer
           )
         END AS rank_score
  FROM public.education_establishments e
  CROSS JOIN input i
  WHERE length(i.raw) >= 2
    AND (
      e.uai = i.possible_uai
      OR e.postal_code LIKE i.raw || '%'
      OR public.normalize_school_name(e.official_name) LIKE '%' || i.normalized || '%'
      OR public.normalize_school_name(e.city) LIKE '%' || i.normalized || '%'
      OR public.normalize_school_name(COALESCE(e.address_line_1, '')) LIKE '%' || i.normalized || '%'
      OR similarity(public.normalize_school_name(e.official_name), i.normalized) > 0.18
      OR similarity(public.normalize_school_name(e.city), i.normalized) > 0.25
    )
  ORDER BY rank_score DESC, e.is_active DESC, e.official_name, e.uai
  LIMIT (SELECT page_size FROM input)
  OFFSET (SELECT page_number * page_size FROM input);
$$;

