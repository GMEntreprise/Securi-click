CREATE OR REPLACE FUNCTION public.normalize_uai(input TEXT)
RETURNS TEXT
LANGUAGE sql
IMMUTABLE
STRICT
SET search_path = pg_catalog
AS $$
  SELECT pg_catalog.upper(
    pg_catalog.regexp_replace(pg_catalog.btrim(input), '\s+', '', 'g')
  );
$$;

CREATE OR REPLACE FUNCTION public.auto_add_school_admin_membership()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.admin_user_id IS NULL THEN
    RETURN NEW;
  END IF;

  INSERT INTO public.school_memberships (school_id, user_id, role, is_active)
  VALUES (NEW.id, NEW.admin_user_id, 'school_admin', true)
  ON CONFLICT (school_id, user_id)
  DO UPDATE SET role = 'school_admin', is_active = true;

  RETURN NEW;
END;
$$;

